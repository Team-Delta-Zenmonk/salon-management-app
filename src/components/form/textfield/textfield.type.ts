  name: Path<T>;
  control: Control<T>;
  label?: string;
  disabled?: boolean;
  maxLength?: number;
  rules?: any;
  identifier: string;
  loading?: boolean;
  endAdornment?: React.ReactElement<SvgIconProps>;
